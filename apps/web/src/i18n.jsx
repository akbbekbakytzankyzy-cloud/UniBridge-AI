const LocaleContext = createContext(null);

function initialLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (["en", "ru", "kk"].includes(saved)) return saved;
  } catch {
    // Storage may be disabled; English remains the predictable default.
  }
  return "en";
}

export function LocaleProvider({ children }) {
  const [language, setLanguage] = useState(initialLanguage);
  useEffect(() => {
    const html = document.documentElement;
    html.lang = language === "kk" ? "kk-KZ" : LOCALES[language];
    html.setAttribute("translate", "no");
    try {
      localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Keep the selection for the current session when storage is unavailable.
    }
  }, [language]);
  const value = useMemo(
    () => ({
      language,
      setLanguage,
      locale: LOCALES[language],
      t: (message) => messages[language]?.[message] || message,
    }),
    [language],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useI18n must be used inside LocaleProvider");
  return value;
}

export function LanguageSelect({ className = "language-select" }) {
  const { language, setLanguage } = useI18n();
  return (
    <select
      className={className}
      aria-label="Language / Тіл / Язык"
      value={language}
      onChange={(event) => setLanguage(event.target.value)}
    >
      <option value="kk">ҚАЗ</option>
      <option value="ru">РУС</option>
      <option value="en">EN</option>
    </select>
  );
}
